/**
 * Small building blocks shared by every domain schema.
 * Owner: frozen (lead). Additive changes only.
 */
import { z } from 'zod';
import { isAbsolutePathLike, isSafePathSegment } from '../core/paths';

/** An absolute Windows (drive or UNC) or POSIX path. Main still normalises it with `node:path`. */
export const AbsPathSchema = z
  .string()
  .min(1)
  .max(32767)
  .refine(isAbsolutePathLike, 'Expected an absolute path');

/** One folder name relative to a session root (`L`, `R`, `CUSTOM`, a typed name, ...). */
export const FolderNameSchema = z
  .string()
  .refine(isSafePathSegment, 'Expected a single, valid folder name');

/** Opaque identifier generated by main (sessions, journal entries, jobs, items). */
export const IdSchema = z.string().min(1).max(200);

/** Identifier chosen by the renderer for a long task, so it can cancel it and match its events. */
export const TaskIdSchema = z
  .string()
  .min(1)
  .max(100)
  .regex(/^[A-Za-z0-9_-]+$/, 'Task ids use letters, digits, - and _');

export const NonNegIntSchema = z.number().int().nonnegative();

/** Milliseconds since the Unix epoch. */
export const TimestampMsSchema = z.number().nonnegative();

/** Request body of channels that take no parameters: `{}` or nothing. */
export const EmptyRequestSchema = z.object({}).optional();

export type AbsPath = z.infer<typeof AbsPathSchema>;
export type FolderName = z.infer<typeof FolderNameSchema>;
export type Id = z.infer<typeof IdSchema>;
export type TaskId = z.infer<typeof TaskIdSchema>;
